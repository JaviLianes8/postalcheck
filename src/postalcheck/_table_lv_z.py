"""Rules for countries LV to Z, transcribed from the libaddressinput ``zip`` patterns.

Patterns match the compact code (no separators, upper case). Examples are the first
``zipex`` code of each country in its canonical layout.
"""

from __future__ import annotations

from ._rules import (
    Rule,
    add_prefix,
    digits,
    drop_prefix,
    rule,
    split_letters,
    tail,
    zip_plus_four,
)

RULES_LV_Z: dict[str, Rule] = {
    # Latvia: the LV- prefix is part of the code; bare digits (accepted by 0.1.0) still
    # validate and normalize to the prefixed form.
    "LV": rule(r"(?:LV)?\d{4}", "LV-1073", add_prefix("LV", "-")),
    "MA": digits(5, "53000"),
    "MC": rule(r"980\d{2}", "98000"),
    "MD": digits(4, "2012"),
    "ME": rule(r"8\d{4}", "81257"),
    "MF": rule(r"9[78][01]\d{2}", "97100"),
    "MG": digits(3, "501"),
    "MH": rule(r"969[67]\d(?:\d{4})?", "96960", zip_plus_four),
    "MK": digits(4, "1314"),
    "MM": digits(5, "11181"),
    "MN": digits(5, "65030"),
    "MP": rule(r"9695[012](?:\d{4})?", "96950", zip_plus_four),
    "MQ": rule(r"9[78]2\d{2}", "97220"),
    "MT": rule(r"[A-Z]{3}\d{2,4}", "NXR 01", split_letters),
    "MU": rule(r"\d{3}(?:\d{2}|[A-Z]{2}\d{3})", "42602"),
    "MV": digits(5, "20026"),
    "MX": digits(5, "02860"),
    "MY": digits(5, "43000"),
    "MZ": digits(4, "1102"),
    "NA": digits(5, "10001"),
    "NC": rule(r"988\d{2}", "98814"),
    "NE": digits(4, "8001"),
    "NF": rule(r"2899", "2899"),
    "NG": digits(6, "930283"),
    "NI": digits(5, "52000"),
    # Netherlands: no leading zero, and never the letter pairs SA, SD or SS.
    "NL": rule(r"[1-9]\d{3}(?:[A-RT-Z][A-Z]|S[BCE-RT-Z])", "1234 AB", tail(" ", 2)),
    "NO": digits(4, "0025"),
    "NP": digits(5, "44601"),
    "NZ": digits(4, "6001"),
    "OM": rule(r"(?:PC)?\d{3}", "133", drop_prefix("PC"), extra=(2,)),
    "PE": rule(r"LIMA\d{1,2}|CALLAO0?\d|[0-2]\d{4}", "LIMA 23", split_letters),
    "PF": rule(r"987\d{2}", "98709"),
    "PG": digits(3, "111"),
    "PH": digits(4, "1008"),
    "PK": digits(5, "44000"),
    "PL": rule(r"\d{5}", "00-950", tail("-", 3)),
    "PM": rule(r"9[78]5\d{2}", "97500"),
    "PN": rule(r"PCRN1ZZ", "PCRN 1ZZ", tail(" ", 3)),
    "PR": rule(r"00[679]\d{2}(?:\d{4})?", "00930", zip_plus_four),
    "PT": rule(r"\d{7}", "2725-079", tail("-", 3)),
    "PW": rule(r"969(?:39|40)(?:\d{4})?", "96940", zip_plus_four),
    "PY": digits(6, "001001"),
    "RE": rule(r"9[78]4\d{2}", "97400"),
    "RO": digits(6, "060274"),
    "RS": rule(r"\d{5,6}", "106314"),
    "RU": digits(6, "247112"),
    "SA": digits(5, "11564"),
    "SD": digits(5, "11042"),
    # Sweden: PostNord writes a space after the third digit (kept from 0.1.0), though
    # libaddressinput lists its examples without one.
    "SE": rule(r"\d{5}", "114 55", tail(" ", 2)),
    "SG": digits(6, "546080"),
    "SH": rule(r"(?:ASCN|STHL)1ZZ", "STHL 1ZZ", tail(" ", 3)),
    "SI": digits(4, "4000"),
    "SJ": digits(4, "9170"),
    "SK": rule(r"\d{5}", "010 01", tail(" ", 2)),
    "SM": rule(r"4789\d", "47890"),
    "SN": digits(5, "12500"),
    "SO": rule(r"[A-Z]{2}\d{5}", "JH 09010", split_letters),
    "SV": rule(r"[1-3][1-7][0-2]\d", "1101"),
    "SZ": rule(r"[HLMS]\d{3}", "H100"),
    "TA": rule(r"TDCU1ZZ", "TDCU 1ZZ", tail(" ", 3)),
    "TC": rule(r"TKCA1ZZ", "TKCA 1ZZ", tail(" ", 3)),
    "TH": digits(5, "10150"),
    "TJ": digits(6, "735450"),
    "TM": digits(6, "744000"),
    "TN": digits(4, "1002"),
    "TR": digits(5, "01960"),
    "TT": digits(6, "500234"),
    "TW": rule(r"\d{3}(?:\d{2,3})?", "104"),
    "TZ": rule(r"\d{4,5}", "6090"),
    "UA": digits(5, "15432"),
    "UM": rule(r"96898", "96898"),
    "US": rule(r"\d{5}(?:\d{4})?", "95014", zip_plus_four),
    "UY": digits(5, "11600"),
    "UZ": digits(6, "702100"),
    "VA": rule(r"00120", "00120"),
    "VC": rule(r"VC\d{4}", "VC0100"),
    "VE": digits(4, "1010"),
    "VG": rule(r"VG\d{4}", "VG1110"),
    "VI": rule(r"008(?:[0-4]\d|5[01])(?:\d{4})?", "00802-1222", zip_plus_four),
    "VN": rule(r"\d{5}\d?", "70010"),
    "WF": rule(r"986\d{2}", "98600"),
    "XK": rule(r"[1-7]\d{4}", "10000"),
    "YT": rule(r"976\d{2}", "97600"),
    "ZA": digits(4, "0083"),
    "ZM": digits(5, "50100"),
}
